package org.conductoross.conductor.common.run;

import com.fasterxml.jackson.annotation.JsonInclude;

/** A user or application recorded against an execution. */
@JsonInclude(JsonInclude.Include.NON_NULL)
public class ExecutionPrincipal {

    public enum Type {
        USER,
        APPLICATION
    }

    private Type type;
    private String id;

    public ExecutionPrincipal() {}

    public ExecutionPrincipal(Type type, String id) {
        this.type = type;
        this.id = id;
    }

    public Type getType() {
        return type;
    }

    public void setType(Type type) {
        this.type = type;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }
}
